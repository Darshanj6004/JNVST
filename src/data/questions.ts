export function practiceSet(subjectId: string, topicId: string, difficulty: string): Question[] {
  let pool = questions.filter((q) => q.subjectId === subjectId);
  if (topicId !== "all") pool = pool.filter((q) => q.topicId === topicId);
  if (difficulty !== "combined") pool = pool.filter((q) => q.difficulty === difficulty);
  // Ensure a usable set even when the authored pool is thin.
  if (pool.length < 5) pool = [...pool, ...questions.filter((q) => !pool.includes(q))].slice(0, 8);
  return pool;
}
